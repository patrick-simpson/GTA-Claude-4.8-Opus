# Run from scratch/fixC (inputs: scratch/audit/osm_extra.json, scratch/audit/pois.json, scratch/streets/tools/warp.py; footprints.json, heights.json in cwd). Part of the footprint pipeline: fp.py -> lidar.py -> gen_ts.py (run from the repo root) -> src/world/footprintData.ts.
import json,sys,os
F=json.load(open('scratch/fixC/footprints.json'))
H={}
if os.path.exists('scratch/fixC/heights.json'): H=json.load(open('scratch/fixC/heights.json'))
code={'house':0,'apt':1,'shop':2,'strip':3,'bigbox':4,'industrial':5,'mill':6,'church':7,'school':8,'civic':8}
rows=[]
for f in F:
    hm=H.get(str(f['id']),0)
    rows.append([round(f['cx']),round(f['cz']),round(min(f['L'],90)),round(min(f['W'],60)),round(f['h'],2),code[f['t']],round(hm*10)])
body=',\n'.join(','.join(str(v) for v in r) for r in rows)
open('src/world/footprintData.ts','w').write("""// Real building footprints for Tepid Falls (generated by scratch/fixC/fp.py + lidar.py from OpenStreetMap, ODbL, warped with the street plan).
// Stride 7: x, z (game metres), long side, short side (real metres), heading of the long side (rad, forward = (sin, cos)), kit
// (0 house, 1 apartment block, 2 shop, 3 strip mall, 4 big-box, 5 industrial, 6 mill, 7 church, 8 school or civic hall),
// LiDAR height in decimetres (USGS 3DEP, Maine LiDAR ME_Maine_LiDAR_NRCS_14; 0 where none). Used by mainlandBuildings.ts.
export const FP_STRIDE = 7;
export const FOOTPRINTS: readonly number[] = [
"""+body+"\n];\n")
print(len(rows),sum(1 for r in rows if r[6]))
