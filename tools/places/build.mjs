// Turns tools/places/pois-real.json (396 named OSM POIs, ODbL, already warped to game coordinates by scratch/audit/pois.py) and
// tools/places/puns.txt (the invented game names) into src/world/directory.ts, and writes tools/places/real-to-pun.json for the lead.
//   node tools/places/build.mjs
// The real names never reach src/: only the puns do. tools/places/ is not part of the build.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url)), root = path.resolve(here, '../..');
const pois = JSON.parse(fs.readFileSync(path.join(here, 'pois-real.json'), 'utf8'));
const CATS = ['food', 'shops', 'services', 'health', 'worship', 'schools', 'civic', 'lodging', 'fuel', 'auto', 'banks', 'offices', 'leisure'];
// Tags that are open ground, not a building: the sign stands at the spot itself.
const OPEN = new Set(['park', 'pitch', 'playground', 'parking', 'artwork', 'bench', 'track', 'golf_course', 'grave_yard', 'shelter', 'viewpoint', 'disused', 'attraction', 'stadium', 'miniature_golf']);
const TAG = { Downtown: 'Downtown', 'Strip/exit127': 'Exit 127', 'Upper Main/exit130': 'Upper Main', 'Far bank': 'Lesser Tepid', Campus: 'Dithers', 'North End': 'North End', 'South End': 'South End', 'West End': 'West End', 'Mills/Water St': 'Mills', other: '' };
const rows = fs.readFileSync(path.join(here, 'puns.txt'), 'utf8').split(/\r?\n/).filter((l) => l && !l.startsWith('#'));
const seen = new Set(), out = [], map = [];
for (const l of rows) {
  const [i0, cat, pun] = l.split('|');
  const skip = i0.startsWith('='), i = Number(i0.replace('=', ''));
  const p = pois[i];
  if (!p || !CATS.includes(cat) || !pun) throw new Error('bad row ' + l);
  if (seen.has(i)) throw new Error('duplicate index ' + i);
  seen.add(i);
  map.push({ index: i, real: p.name, pun, cat, osm: p.cat, x: p.x, z: p.z, listed: !skip });
  if (skip) continue;
  const sub = p.cat.split('=')[1].split(';')[0];
  out.push({ pun, cat: CATS.indexOf(cat), x: p.x, z: p.z, open: OPEN.has(sub) ? 1 : 0, tag: TAG[p.district] ?? '', i });
}
if (seen.size !== pois.length) throw new Error(`rows ${seen.size} != pois ${pois.length}`);
// Same name twice (chains): the second and later get their district, then a number.
const used = new Map();
for (const e of out) {
  const n = used.get(e.pun) ?? 0; used.set(e.pun, n + 1);
}
const cnt = new Map(), ROM = ['', ' II', ' III', ' IV', ' V', ' VI'];
for (const e of out) {
  if (used.get(e.pun) > 1) {
    const base = `${e.pun} (${e.tag || 'Tepid Falls'})`, k = cnt.get(base) ?? 0; cnt.set(base, k + 1);
    e.name = base + ROM[k];
  } else e.name = e.pun;
}
for (const m of map) { const e = out.find((o) => o.i === m.index); if (e) m.name = e.name; }
const q = (s) => JSON.stringify(s);
let ts = `// The business directory: ${out.length} invented names for the places OpenStreetMap lists in Waterville (map data © OpenStreetMap contributors, ODbL).
// GENERATED by tools/places/build.mjs from tools/places/puns.txt. Do not edit by hand. No real name or brand is in this file.
// [name, category, x, z, open ground (0 or 1)]; x, z are where the place stands in the game's town; world/business.ts snaps it to a building.
export const CATEGORIES = ${q(CATS)} as const;
export type Category = typeof CATEGORIES[number];
export const CATEGORY_NAME: Record<Category, string> = { food: 'Food & drink', shops: 'Shops', services: 'Services', health: 'Health', worship: 'Worship', schools: 'Schools', civic: 'Civic', lodging: 'Lodging', fuel: 'Fuel', auto: 'Cars', banks: 'Banks', offices: 'Offices', leisure: 'Leisure' };
export const DIRECTORY: readonly (readonly [string, number, number, number, number])[] = [\n`;
for (const e of out) ts += ` [${q(e.name)}, ${e.cat}, ${e.x}, ${e.z}, ${e.open}],\n`;
ts += '];\n';
fs.writeFileSync(path.join(root, 'src/world/directory.ts'), ts);
fs.writeFileSync(path.join(here, 'real-to-pun.json'), JSON.stringify(map, null, 1));
console.log('listed', out.length, 'of', pois.length, 'cats', CATS.map((c, k) => c + ':' + out.filter((e) => e.cat === k).length).join(' '));
